const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getServices: () => ipcRenderer.invoke('get-services'),
  getState: () => ipcRenderer.invoke('get-state'),
  updateState: (patch) => ipcRenderer.invoke('update-state', patch),
  getCatalog: () => ipcRenderer.invoke('get-catalog'),
  refresh: (scope) => ipcRenderer.invoke('refresh', scope),
  getDetails: (game) => ipcRenderer.invoke('get-details', game),
  getRatings: () => ipcRenderer.invoke('get-ratings'),
  onRatings: (fn) => ipcRenderer.on('ratings', (_e, msg) => fn(msg)),
  getPsBlogProgress: () => ipcRenderer.invoke('get-psblog-progress'),
  onPsBlogProgress: (fn) => ipcRenderer.on('psblog-progress', (_e, p) => fn(p)),
  onCatalogChanged: (fn) => ipcRenderer.on('catalog-changed', () => fn()),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  launch: (url) => ipcRenderer.invoke('launch', url),
  steamInstalled: (appid) => ipcRenderer.invoke('steam-installed', appid),
  watchSales: (list) => ipcRenderer.invoke('watch-sales', list),
  exportBackup: (opts) => ipcRenderer.invoke('export-backup', opts),
  importBackup: () => ipcRenderer.invoke('import-backup'),
  importSteam: (profile, key) => ipcRenderer.invoke('import-steam', { profile, key }),
  forgetSteam: () => ipcRenderer.invoke('forget-steam'),
  importAchievements: (kind, secret) => ipcRenderer.invoke('import-achievements', { kind, secret }),
  forgetAchievements: (kind) => ipcRenderer.invoke('forget-achievements', kind),
  onStateChanged: (fn) => ipcRenderer.on('state-changed', (_e, s) => fn(s)),
  onShowView: (fn) => ipcRenderer.on('show-view', (_e, view) => fn(view)),
  getPrices: () => ipcRenderer.invoke('get-prices'),
  lookupPrices: (games) => ipcRenderer.invoke('lookup-prices', games),
  onPrices: (fn) => ipcRenderer.on('prices', (_e, msg) => fn(msg)),
  getFree: () => ipcRenderer.invoke('get-free'),
  refreshFree: () => ipcRenderer.invoke('refresh-free'),
  onFreeChanged: (fn) => ipcRenderer.on('free-changed', () => fn()),
  getUpdate: () => ipcRenderer.invoke('get-update'),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  downloadUpdate: () => ipcRenderer.invoke('download-update'),
  installUpdate: () => ipcRenderer.invoke('install-update'),
  onUpdateChanged: (fn) => ipcRenderer.on('update-changed', (_e, st) => fn(st)),
  getSync: () => ipcRenderer.invoke('get-sync'),
  chooseSyncFolder: () => ipcRenderer.invoke('choose-sync-folder'),
  stopSync: () => ipcRenderer.invoke('stop-sync'),
  setSyncAccounts: (on) => ipcRenderer.invoke('set-sync-accounts', on),
  syncNow: () => ipcRenderer.invoke('sync-now'),
  onSyncStatus: (fn) => ipcRenderer.on('sync-status', (_e, st) => fn(st)),
  onRefreshProgress: (fn) => ipcRenderer.on('refresh-progress', (_e, msg) => fn(msg)),
});
